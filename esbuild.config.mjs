import esbuild from 'esbuild';
import process from 'process';
import { readFileSync } from 'node:fs';
import { builtinModules } from 'node:module';

// main.js is all a user installs, so the bundled reladraw's Apache-2.0 license and NOTICE ride along in it.
const notices = ['LICENSE', 'node_modules/reladraw/NOTICE', 'node_modules/reladraw/LICENSE']
	.map((file) => readFileSync(file, 'utf8').replaceAll('*/', '* /').trim())
	.join('\n\n---\n\n');

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

Right Of is MIT licensed. It bundles reladraw (https://github.com/reladraw/reladraw),
which is Apache-2.0 licensed. The license texts and notices follow.

${notices}
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
